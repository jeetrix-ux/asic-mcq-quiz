"""Regenerate data.js from the MCQ practice-sheet unit files.

    python tools/build_data.py ~/sem5notes/asic-flow/mcq-practice/source/units > data.js
"""
import json, pathlib, re, sys

units = pathlib.Path(sys.argv[1])
H2 = re.compile(r'<h2>Part ([A-C])')
H3 = re.compile(r'<h3 id="([a-z0-9]+)">(.*?)</h3>')
MCQ = re.compile(r'<div class="mcq" data-ans="([a-d])" data-ref="(.*?)" data-why="(.*?)">\s*'
                 r'<p class="stem">(.*?)</p>\s*<div class="opts[^"]*">(.*?)</div>\s*</div>', re.S)
OPT = re.compile(r'<span><b>\(([a-d])\)</b>\s*(.*?)</span>', re.S)
TOK = re.compile(r'<h2>Part [A-C].*?</h2>|<h3 id="[a-z0-9]+">.*?</h3>|<div class="mcq".*?</div>\s*</div>', re.S)

sections, qs = [], []
sec = None
for f in sorted(units.glob("*.html")):
    for tok in TOK.findall(f.read_text(encoding="utf8")):
        if tok.startswith("<h3"):
            sid, title = H3.match(tok).groups()
            title = re.sub(r"^[A-Z]\d+\s*&nbsp;", "", title).strip()
            sec = {"id": sid, "title": title, "part": sid[0].upper()}
            sections.append(sec)
        elif tok.startswith('<div class="mcq"'):
            ans, ref, why, stem, opts = MCQ.match(tok).groups()
            o = OPT.findall(opts)
            assert len(o) == 4, stem
            qs.append({"n": len(qs) + 1, "s": sec["id"], "q": stem.strip(),
                       "o": [t.strip() for _, t in o], "a": "abcd".index(ans),
                       "why": why, "ref": ref})
assert len(qs) == 200, len(qs)
for s in sections:
    s["count"] = sum(q["s"] == s["id"] for q in qs)
sections = [s for s in sections if s["count"]]
sys.stdout.write("// generated by tools/build_data.py, do not edit by hand\n")
sys.stdout.write("window.QUIZ = " + json.dumps({"sections": sections, "questions": qs},
                                                ensure_ascii=False, indent=0) + ";\n")
